// stars.swift: turn the Bright Star Catalogue table (data/bsc5-vmag5.5.tsv,
// VizieR asu-tsv, V/50/catalog, Vmag < 5.5) into compact star data for both
// renderers: Sources/wallframes/Stars.swift and windows/src/Stars.cs.
//
//   swift tools/stars.swift
//
// One star per line: RA and Dec (J2000, degrees), V magnitude, B−V color
// index (0.65, sun-like, where the catalogue has none).

import Foundation

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let text = try String(contentsOf: root.appendingPathComponent("data/bsc5-vmag5.5.tsv"), encoding: .utf8)

func number(_ s: Substring) -> Double? { Double(s.trimmingCharacters(in: .whitespaces)) }

var lines: [String] = []
for row in text.split(separator: "\n") where !row.hasPrefix("#") {
    let f = row.split(separator: "\t", omittingEmptySubsequences: false)
    guard f.count >= 5, number(f[0]) != nil else { continue }  // header and unit rows have no HR number
    let ra = f[1].split(separator: " ").compactMap { Double($0) }
    let dec = f[2].trimmingCharacters(in: .whitespaces)
    let d = dec.dropFirst().split(separator: " ").compactMap { Double($0) }
    guard ra.count == 3, d.count == 3, let mag = number(f[3]) else { continue }
    let raDeg = (ra[0] + ra[1] / 60 + ra[2] / 3600) * 15
    let decDeg = (dec.hasPrefix("-") ? -1 : 1) * (d[0] + d[1] / 60 + d[2] / 3600)
    let bv = number(f[4]) ?? 0.65
    lines.append(String(format: "%.3f %.3f %.2f %.2f", raDeg, decDeg, mag, bv))
}

let header = """
    Generated by tools/stars.swift from data/bsc5-vmag5.5.tsv: the Bright Star
    Catalogue, 5th revised ed. (Hoffleit & Warren 1991), via VizieR (CDS,
    Strasbourg). \(lines.count) stars brighter than V = 5.5, one per line: RA and Dec
    (J2000, degrees), V magnitude, B-V color index.
    """
let swift = header.split(separator: "\n").map { "// " + $0 }.joined(separator: "\n")
    + "\n\nlet brightStarData = \"\"\"\n" + lines.joined(separator: "\n") + "\n\"\"\"\n"
let cs = header.split(separator: "\n").map { "// " + $0 }.joined(separator: "\n")
    + "\n\nstatic class StarData\n{\n    public const string Text = @\"" + lines.joined(separator: "\n") + "\";\n}\n"
try swift.write(to: root.appendingPathComponent("Sources/wallframes/Stars.swift"), atomically: true, encoding: .utf8)
try cs.write(to: root.appendingPathComponent("windows/src/Stars.cs"), atomically: true, encoding: .utf8)
print("\(lines.count) stars")
